-- SOLO LECTURA. Ejecutar como SA_REDUCCION conectado a XEPDB1.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 160
SET PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
  n NUMBER;
  PROCEDURE assert_count(p_tipo VARCHAR2, p_esperado NUMBER) IS
  BEGIN
    SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_TYPE=p_tipo;
    DBMS_OUTPUT.PUT_LINE(p_tipo||': '||n||' (esperado: '||p_esperado||')');
    IF n<>p_esperado THEN RAISE_APPLICATION_ERROR(-20901,'Conteo inesperado: '||p_tipo); END IF;
  END;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'SA_REDUCCION'
     OR SYS_CONTEXT('USERENV','CON_NAME')<>'XEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20900,'Conectar como SA_REDUCCION en XEPDB1');
  END IF;
  assert_count('TABLE',21);
  assert_count('SEQUENCE',15);
  assert_count('TRIGGER',22);
  SELECT COUNT(*) INTO n FROM USER_OBJECTS
   WHERE OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY')
     AND OBJECT_NAME IN ('PKG_ESTUDIANTE','PKG_ADMINISTRADOR','PKG_ASPIRANTE') AND STATUS='VALID';
  DBMS_OUTPUT.PUT_LINE('Paquetes y cuerpos VALID: '||n||' (esperado: 6)');
  IF n<>6 THEN RAISE_APPLICATION_ERROR(-20902,'Paquetes incompletos o invalidos'); END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE STATUS<>'VALID';
  DBMS_OUTPUT.PUT_LINE('Objetos invalidos: '||n);
  IF n<>0 THEN RAISE_APPLICATION_ERROR(-20903,'Existen objetos invalidos'); END IF;
  DBMS_OUTPUT.PUT_LINE('OK: estructura y paquetes verificados');
END;
/
PROMPT ===== DETALLE DE OBJETOS =====
SELECT OBJECT_TYPE, STATUS, COUNT(*) CANTIDAD FROM USER_OBJECTS
 GROUP BY OBJECT_TYPE,STATUS ORDER BY OBJECT_TYPE,STATUS;
PROMPT ===== ERRORES DE COMPILACION (DEBE ESTAR VACIO) =====
SELECT NAME,TYPE,LINE,POSITION,TEXT FROM USER_ERRORS ORDER BY NAME,SEQUENCE;
EXIT SUCCESS