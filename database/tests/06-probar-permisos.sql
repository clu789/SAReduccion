-- SOLO LECTURA. Ejecutar como SYSDBA DENTRO DE XEPDB1.
-- Verifica roles y permisos EXECUTE, sin iniciar sesion como cada perfil.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET LINESIZE 180
SET PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
  n NUMBER;
  PROCEDURE verificar(p_sql VARCHAR2,p_etiqueta VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql INTO n;
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20910,'Falta: '||p_etiqueta); END IF;
    DBMS_OUTPUT.PUT_LINE('OK: '||p_etiqueta);
  END;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'SYS'
    OR SYS_CONTEXT('USERENV','CON_NAME')<>'XEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20911,'Ejecutar como SYSDBA en XEPDB1');
  END IF;
  verificar(q'[SELECT COUNT(*) FROM DBA_USERS WHERE USERNAME='SA_REDUCCION']','Esquema SA_REDUCCION');
  verificar(q'[SELECT COUNT(*) FROM DBA_ROLE_PRIVS WHERE GRANTEE='ALU_21281181' AND GRANTED_ROLE='ROL_SAR_ESTUDIANTE_SIM']','Rol estudiante asignado');
  verificar(q'[SELECT COUNT(*) FROM DBA_ROLE_PRIVS WHERE GRANTEE='SA01' AND GRANTED_ROLE='ROL_SAR_ADMIN_SIM']','Rol administrador asignado');
  verificar(q'[SELECT COUNT(*) FROM DBA_TAB_PRIVS WHERE OWNER='SA_REDUCCION' AND TABLE_NAME='PKG_ESTUDIANTE' AND GRANTEE='ROL_SAR_ESTUDIANTE_SIM' AND PRIVILEGE='EXECUTE']','EXECUTE paquete estudiante');
  verificar(q'[SELECT COUNT(*) FROM DBA_TAB_PRIVS WHERE OWNER='SA_REDUCCION' AND TABLE_NAME='PKG_ADMINISTRADOR' AND GRANTEE='ROL_SAR_ADMIN_SIM' AND PRIVILEGE='EXECUTE']','EXECUTE paquete administrador');
  SELECT COUNT(*) INTO n FROM DBA_TAB_PRIVS
   WHERE OWNER='SA_REDUCCION'
     AND GRANTEE IN ('ROL_SAR_ESTUDIANTE_SIM','ROL_SAR_ADMIN_SIM')
     AND PRIVILEGE IN ('SELECT','INSERT','UPDATE','DELETE');
  IF n<>0 THEN RAISE_APPLICATION_ERROR(-20912,'Roles con acceso directo a tablas: '||n); END IF;
  DBMS_OUTPUT.PUT_LINE('OK: sin CRUD directo concedido a roles');
  SELECT COUNT(*) INTO n FROM DBA_TAB_PRIVS
   WHERE OWNER='SA_REDUCCION' AND (
     (GRANTEE='ROL_SAR_ESTUDIANTE_SIM' AND TABLE_NAME='PKG_ADMINISTRADOR' AND PRIVILEGE='EXECUTE') OR
     (GRANTEE='ROL_SAR_ADMIN_SIM' AND TABLE_NAME='PKG_ESTUDIANTE' AND PRIVILEGE='EXECUTE'));
  IF n<>0 THEN RAISE_APPLICATION_ERROR(-20913,'Permisos EXECUTE cruzados detectados'); END IF;
  DBMS_OUTPUT.PUT_LINE('OK: sin EXECUTE cruzado');
  DBMS_OUTPUT.PUT_LINE('OK: auditoria de privilegios superada');
END;
/
PROMPT ===== PERMISOS SOBRE OBJETOS DE LA APLICACION =====
SELECT GRANTEE,OWNER,TABLE_NAME,PRIVILEGE FROM DBA_TAB_PRIVS
 WHERE OWNER='SA_REDUCCION' AND GRANTEE IN ('ROL_SAR_ESTUDIANTE_SIM','ROL_SAR_ADMIN_SIM')
 ORDER BY GRANTEE,TABLE_NAME;
EXIT SUCCESS